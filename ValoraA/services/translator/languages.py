"""
services/translator/languages.py

Verified Capability Registry for Indian Regional and Global Languages.
Tracks Speech Recognition (STT), Machine Translation, and Text-to-Speech (TTS)
capabilities with exact native scripts, locales, writing directions, and neural voices.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Optional


@dataclass(frozen=True)
class VoiceOption:
    id: str
    name: str
    gender: str
    locale: str
    provider: str = "edge-tts"


@dataclass(frozen=True)
class LanguageCapability:
    code: str  # Short ISO code (e.g. 'hi')
    locale: str  # Full BCP-47 locale (e.g. 'hi-IN')
    english_name: str
    native_name: str
    category: str  # 'indian' | 'global'
    script: str
    direction: str = "ltr"  # 'ltr' | 'rtl'
    stt_supported: bool = True
    stt_locale: str = ""
    translation_supported: bool = True
    tts_supported: bool = True
    default_voice: Optional[str] = None
    voices: List[VoiceOption] = field(default_factory=list)

    @property
    def display_label(self) -> str:
        return f"{self.english_name} — {self.native_name}"

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["name"] = self.english_name
        d["native"] = self.native_name
        d["display_label"] = self.display_label
        d["stt"] = self.stt_supported
        d["tts"] = self.tts_supported
        d["rtl"] = self.direction == "rtl"
        return d


