# Combined master registry
ALL_LANGUAGES: Dict[str, LanguageCapability] = {**INDIAN_LANGUAGES, **GLOBAL_LANGUAGES}


def get_language_capability(code: str) -> Optional[LanguageCapability]:
    """Retrieve capability descriptor by short code or locale."""
    if not code:
        return None
    code_lower = code.lower().strip()
    if code_lower in ALL_LANGUAGES:
        return ALL_LANGUAGES[code_lower]
    # Check locale matching (e.g. 'en-us' -> 'en', 'hi-in' -> 'hi')
    for lang in ALL_LANGUAGES.values():
        if lang.locale.lower() == code_lower or lang.code.lower() == code_lower:
            return lang
    # Prefix fallback (e.g. 'hi' for 'hi-IN')
    prefix = code_lower.split("-")[0]
    if prefix in ALL_LANGUAGES:
        return ALL_LANGUAGES[prefix]
    return None


def list_language_capabilities() -> Dict[str, List[Dict[str, Any]]]:
    """Return categorized lists for frontend selectors."""
    return {
        "indian": [lang.to_dict() for lang in INDIAN_LANGUAGES.values()],
        "global": [lang.to_dict() for lang in GLOBAL_LANGUAGES.values()],
        "all": [lang.to_dict() for lang in ALL_LANGUAGES.values()],
    }
